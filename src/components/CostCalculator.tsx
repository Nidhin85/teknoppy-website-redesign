/**
 * Website Cost Calculator island (/website-cost-calculator-kerala/).
 *
 * Every rupee figure it can show comes from `config`, which is fed by
 * `src/data/pages/website-cost-calculator-kerala.json` — and those bands are
 * copied from the pricing tables already published on the Web Design,
 * WordPress, Ecommerce and Web Application pillar pages. The page copy promises
 * "the range you see is the range you get quoted", so the calculator must never
 * compute a number from a rate that isn't published somewhere on the site.
 *
 * Add-ons therefore render as "Quoted separately" until someone fills in their
 * `min`/`max` in the JSON: no published add-on rate exists yet, and inventing
 * one would break that promise.
 */
import { useMemo, useState } from 'react';
import { ArrowRight, Check, Mail, Phone } from 'lucide-react';

interface Tier {
  id: string;
  label: string;
  detail?: string;
  min: number;
  max: number;
  openEnded?: boolean;
  source?: string;
}

interface TypeOption {
  id: string;
  label: string;
  blurb?: string;
  tiers: Tier[];
}

interface Addon {
  id: string;
  label: string;
  text?: string;
  min?: number | null;
  max?: number | null;
}

interface Config {
  types: TypeOption[];
  addons?: Addon[];
  included?: string[];
  stepLabels?: string[];
  quote?: { label: string; href: string };
  call?: { label: string; href: string };
  emailSubject?: string;
  note?: string;
  complexNote?: string;
}

const inr = (n: number) => `Rs. ${n.toLocaleString('en-IN')}`;

// "Rs. 25,000 – 50,000", matching how the pillar pricing tables are written —
// the Rs. prefix appears once, not on both ends of the range.
const band = (min: number, max: number, openEnded?: boolean) =>
  `${inr(min)} – ${max.toLocaleString('en-IN')}${openEnded ? '+' : ''}`;

export default function CostCalculator({ config }: { config: Config }) {
  const types = config.types ?? [];
  const addons = config.addons ?? [];
  const [typeId, setTypeId] = useState(types[0]?.id ?? '');
  const [tierId, setTierId] = useState(types[0]?.tiers?.[0]?.id ?? '');
  const [picked, setPicked] = useState<string[]>([]);

  const type = types.find((t) => t.id === typeId) ?? types[0];
  const tier = type?.tiers.find((t) => t.id === tierId) ?? type?.tiers[0];

  const chosenAddons = addons.filter((a) => picked.includes(a.id));
  const pricedAddons = chosenAddons.filter((a) => a.min != null && a.max != null);
  const unpricedAddons = chosenAddons.filter((a) => a.min == null || a.max == null);

  const total = useMemo(() => {
    if (!tier) return null;
    return {
      min: tier.min + pricedAddons.reduce((sum, a) => sum + (a.min ?? 0), 0),
      max: tier.max + pricedAddons.reduce((sum, a) => sum + (a.max ?? 0), 0),
      openEnded: tier.openEnded
    };
  }, [tier, pricedAddons]);

  const selectType = (id: string) => {
    setTypeId(id);
    setTierId(types.find((t) => t.id === id)?.tiers[0]?.id ?? '');
  };

  const toggleAddon = (id: string) =>
    setPicked((prev) => (prev.includes(id) ? prev.filter((a) => a !== id) : [...prev, id]));

  // "Email yourself the estimate" — a prefilled mailto, so the breakdown reaches
  // the visitor's inbox without asking for an address first (the page promises
  // no email is required to see a number).
  const mailHref = useMemo(() => {
    if (!type || !tier || !total) return '#';
    const lines = [
      `Website type: ${type.label}`,
      `Scope: ${tier.label}`,
      `Base range: ${band(tier.min, tier.max, tier.openEnded)}`,
      ...pricedAddons.map((a) => `Add-on — ${a.label}: ${band(a.min as number, a.max as number)}`),
      ...unpricedAddons.map((a) => `Add-on — ${a.label}: quoted separately`),
      '',
      `Estimated range: ${band(total.min, total.max, total.openEnded)}`,
      '',
      'Estimate generated by the Teknoppy Website Cost Calculator.',
      'Development cost only — hosting, domain and maintenance are quoted separately.',
      'https://teknoppy.com/website-cost-calculator-kerala/'
    ];
    return `mailto:?subject=${encodeURIComponent(config.emailSubject ?? 'My Teknoppy website cost estimate')}&body=${encodeURIComponent(lines.join('\n'))}`;
  }, [type, tier, total, pricedAddons, unpricedAddons, config.emailSubject]);

  const stepLabels = config.stepLabels ?? [
    'Choose your website type',
    'Choose your scope',
    'Add-ons'
  ];

  if (!type || !tier) return null;

  return (
    <div className="grid lg:grid-cols-12 gap-6 lg:gap-8 items-start">
      {/* CHOICES */}
      <div className="lg:col-span-7 bg-white rounded-[2rem] border border-neutral-100 p-6 sm:p-8 shadow-[0_24px_60px_-30px_rgba(0,0,0,0.2)] space-y-8">
        <fieldset>
          <legend className="flex items-center gap-3 mb-4">
            <span className="w-7 h-7 rounded-full bg-primary text-white text-xs font-black flex items-center justify-center flex-shrink-0">1</span>
            <span className="text-sm font-black text-neutral-900 uppercase tracking-widest">{stepLabels[0]}</span>
          </legend>
          <div className="grid sm:grid-cols-2 gap-3">
            {types.map((t) => (
              <button
                key={t.id}
                type="button"
                onClick={() => selectType(t.id)}
                aria-pressed={t.id === typeId}
                className={`text-left rounded-2xl border p-4 transition-all duration-200 cursor-pointer ${
                  t.id === typeId
                    ? 'border-primary bg-primary/5 shadow-[0_10px_24px_-16px_rgba(240,90,44,0.5)]'
                    : 'border-neutral-200 bg-white hover:border-primary/40'
                }`}
              >
                <span className="block text-sm font-black text-neutral-900 leading-snug">{t.label}</span>
                {t.blurb && <span className="block text-xs font-semibold text-neutral-500 mt-1 leading-relaxed">{t.blurb}</span>}
              </button>
            ))}
          </div>
        </fieldset>

        <fieldset>
          <legend className="flex items-center gap-3 mb-4">
            <span className="w-7 h-7 rounded-full bg-primary text-white text-xs font-black flex items-center justify-center flex-shrink-0">2</span>
            <span className="text-sm font-black text-neutral-900 uppercase tracking-widest">{stepLabels[1]}</span>
          </legend>
          <div className="divide-y divide-neutral-100 border border-neutral-200 rounded-2xl overflow-hidden">
            {type.tiers.map((t) => (
              <label
                key={t.id}
                className={`flex items-start gap-3 p-4 cursor-pointer transition-colors ${t.id === tier.id ? 'bg-primary/5' : 'bg-white hover:bg-neutral-50'}`}
              >
                <input
                  type="radio"
                  name="cc-tier"
                  value={t.id}
                  checked={t.id === tier.id}
                  onChange={() => setTierId(t.id)}
                  className="mt-1 accent-[#F05A2C] w-4 h-4 flex-shrink-0"
                />
                <span className="min-w-0 flex-grow">
                  <span className="block text-sm font-bold text-neutral-900 leading-snug">{t.label}</span>
                  {t.detail && <span className="block text-xs font-semibold text-neutral-500 mt-1 leading-relaxed">{t.detail}</span>}
                </span>
                <span className="text-xs font-black text-primary whitespace-nowrap tabular-nums pt-0.5">
                  {band(t.min, t.max, t.openEnded)}
                </span>
              </label>
            ))}
          </div>
        </fieldset>

        {addons.length > 0 && (
          <fieldset>
            <legend className="flex items-center gap-3 mb-4">
              <span className="w-7 h-7 rounded-full bg-primary text-white text-xs font-black flex items-center justify-center flex-shrink-0">3</span>
              <span className="text-sm font-black text-neutral-900 uppercase tracking-widest">{stepLabels[2]}</span>
            </legend>
            <div className="grid sm:grid-cols-2 gap-3">
              {addons.map((a) => {
                const on = picked.includes(a.id);
                return (
                  <label
                    key={a.id}
                    className={`flex items-start gap-3 rounded-2xl border p-4 cursor-pointer transition-all duration-200 ${
                      on ? 'border-primary bg-primary/5' : 'border-neutral-200 bg-white hover:border-primary/40'
                    }`}
                  >
                    <input
                      type="checkbox"
                      checked={on}
                      onChange={() => toggleAddon(a.id)}
                      className="mt-0.5 accent-[#F05A2C] w-4 h-4 flex-shrink-0"
                    />
                    <span className="min-w-0">
                      <span className="block text-sm font-bold text-neutral-900 leading-snug">{a.label}</span>
                      <span className="block text-xs font-semibold text-neutral-500 mt-1 leading-relaxed">
                        {a.min != null && a.max != null ? band(a.min, a.max) : a.text ?? 'Quoted separately'}
                      </span>
                    </span>
                  </label>
                );
              })}
            </div>
          </fieldset>
        )}
      </div>

      {/* ESTIMATE */}
      <aside className="lg:col-span-5 lg:sticky lg:top-28 space-y-5">
        <div className="theme-keep-light bg-neutral-950 text-white rounded-[2rem] p-6 sm:p-8 shadow-[0_24px_60px_-30px_rgba(0,0,0,0.4)] relative overflow-hidden">
          <div className="absolute -top-16 -right-16 w-56 h-56 rounded-full bg-primary/20 blur-[80px] pointer-events-none" />
          <div className="relative z-10">
            <span className="block text-[11px] font-black text-neutral-500 uppercase tracking-[0.18em] mb-3">Your estimated range</span>
            <span className="block text-3xl sm:text-[34px] font-black text-primary leading-none tracking-tight tabular-nums">
              {total && band(total.min, total.max, total.openEnded)}
            </span>

            <dl className="mt-7 pt-6 border-t border-white/10 space-y-3">
              <div className="flex items-baseline justify-between gap-4">
                <dt className="text-xs font-bold text-neutral-400 leading-snug">{type.label} — {tier.label}</dt>
                <dd className="text-xs font-black text-white whitespace-nowrap tabular-nums">{band(tier.min, tier.max, tier.openEnded)}</dd>
              </div>
              {pricedAddons.map((a) => (
                <div key={a.id} className="flex items-baseline justify-between gap-4">
                  <dt className="text-xs font-bold text-neutral-400 leading-snug">{a.label}</dt>
                  <dd className="text-xs font-black text-white whitespace-nowrap tabular-nums">{band(a.min as number, a.max as number)}</dd>
                </div>
              ))}
              {unpricedAddons.map((a) => (
                <div key={a.id} className="flex items-baseline justify-between gap-4">
                  <dt className="text-xs font-bold text-neutral-400 leading-snug">{a.label}</dt>
                  <dd className="text-xs font-black text-neutral-500 whitespace-nowrap">Quoted separately</dd>
                </div>
              ))}
            </dl>

            {config.included && config.included.length > 0 && (
              <ul className="mt-6 pt-6 border-t border-white/10 space-y-2">
                {config.included.map((item) => (
                  <li key={item} className="flex items-start gap-2 text-xs font-semibold text-neutral-300 leading-relaxed">
                    <span className="w-4 h-4 rounded-full bg-primary/15 text-primary flex items-center justify-center flex-shrink-0 mt-0.5">
                      <Check className="w-2.5 h-2.5" />
                    </span>
                    {item}
                  </li>
                ))}
              </ul>
            )}

            <div className="mt-7 space-y-3">
              {config.quote && (
                <a
                  href={config.quote.href}
                  className="w-full inline-flex items-center justify-center gap-2.5 px-6 py-3.5 text-sm font-bold text-white bg-primary rounded-full shadow-[0_6px_20px_rgba(240,90,44,0.35)] hover:bg-primary/95 transition-all duration-300"
                >
                  {config.quote.label}
                  <ArrowRight className="w-4 h-4" />
                </a>
              )}
              <a
                href={mailHref}
                className="w-full inline-flex items-center justify-center gap-2.5 px-6 py-3.5 text-sm font-bold text-white border border-white/20 rounded-full hover:bg-white/5 transition-all duration-300"
              >
                <Mail className="w-4 h-4" />
                Email myself this estimate
              </a>
              {config.call && (
                <a
                  href={config.call.href}
                  className="w-full inline-flex items-center justify-center gap-2.5 px-6 py-3.5 text-sm font-bold text-neutral-300 hover:text-white transition-colors"
                >
                  <Phone className="w-4 h-4" />
                  {config.call.label}
                </a>
              )}
            </div>
          </div>
        </div>

        {(config.note || config.complexNote) && (
          <div className="bg-white rounded-3xl border border-neutral-100 p-5 shadow-[0_10px_24px_-16px_rgba(0,0,0,0.08)] space-y-3">
            {config.note && <p className="text-xs text-neutral-500 font-semibold leading-relaxed">{config.note}</p>}
            {config.complexNote && <p className="text-xs text-neutral-500 font-semibold leading-relaxed">{config.complexNote}</p>}
          </div>
        )}
      </aside>
    </div>
  );
}
